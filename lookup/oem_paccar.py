def paccar_family(model: str | None) -> str | None:
    """MX engine family from a CI model string, or None."""
    m = (model or '').upper()
    if any(t in m for t in ('MX-11', 'MX11', 'MX-13', 'MX13')):
        return 'mx_11_13'
    return None


