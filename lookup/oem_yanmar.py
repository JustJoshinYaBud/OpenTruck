def spn_fmi_for_pcode(code: str, model: str | None = None):
    """(SPN, FMI) for an P-code such as 'P0193', or None.

    The maker's own code rides the second element of the single
    table's rows; this index is derived from it, so there is no
    separate cross-reference table. The model is accepted but
    ignored - one table per brand, no family gating.
    """
    return _YANMAR_CODE_INDEX.get((code or '').strip().upper())

